import { createHash } from 'node:crypto';
import { readFile, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
if (process.argv.includes('--write')) throw new Error('The baseline is deployed and immutable. Create a new staging migration instead.');
const source = resolve(root, 'supabase/migrations');
const destination = resolve(root, 'staging/supabase/migrations');
const exclusions = {
  '20260704083408_d80d0ccf-470a-4694-be11-0421febd259c.sql': 'Grants super_admin to a source-project UUID that does not exist in a fresh project.',
  '20260708055928_6c5de206-4aeb-4d41-86a9-c05c2764cd67.sql': 'Creates an administrator with an embedded password. Owner bootstrap must be manual.',
};
// This baseline was deployed on 2026-09-07. Later changes must be new migrations
// in staging/supabase/migrations, never regenerated into this applied baseline.
const files = (await readdir(source)).filter(file => file.endsWith('.sql') && file.slice(0, 14) <= '20260907094411').sort();
const baselines = (await readdir(destination)).filter(file => file.endsWith('_careconnect_fresh_baseline.sql'));
if (baselines.length !== 1) throw new Error('Create exactly one careconnect_fresh_baseline migration with the Supabase CLI first.');
const manifest = [];
const blocks = [
  '-- FRESH EMPTY PROJECT ONLY. Never apply this baseline to an existing application database.',
  '-- Generated by scripts/build-staging-baseline.mjs; see staging/README.md.',
  '-- Historical migrations remain unchanged. No Auth users or privileged demo accounts are seeded.',
  `DO $$ BEGIN
    IF EXISTS (SELECT 1 FROM pg_tables WHERE schemaname = 'public')
       OR EXISTS (SELECT 1 FROM auth.users) THEN
      RAISE EXCEPTION 'CareConnect fresh baseline requires an empty public schema and no Auth users';
    END IF;
  END $$;`,
];
for (const file of files) {
  const original = (await readFile(resolve(source, file), 'utf8')).replace(/\r\n/g, '\n');
  const excluded = exclusions[file];
  manifest.push({ file, sha256: createHash('sha256').update(original).digest('hex'), action: excluded ? 'excluded' : 'included', reason: excluded ?? null });
  if (excluded) continue;
  // An enum's complete value set must exist at CREATE TYPE time so this fresh
  // baseline can be applied atomically in one transaction.
  const sql = original
    .replace("CREATE TYPE public.app_role AS ENUM ('patient','provider','facility','admin');", "CREATE TYPE public.app_role AS ENUM ('patient','provider','facility','admin','super_admin');")
    .replace("CREATE TYPE public.care_status AS ENUM ('open','accepted','completed','cancelled');", "CREATE TYPE public.care_status AS ENUM ('open','accepted','completed','cancelled','failed');")
    .replace(/ALTER TYPE public\.(?:app_role|care_status) ADD VALUE IF NOT EXISTS '(?:super_admin|failed)';/g, '-- Enum value already declared in the fresh baseline.');
  blocks.push(`\n-- SOURCE: ${file}\n${sql.trim()}\n`);
}
const output = blocks.join('\n') + '\n';
if (/INSERT\s+INTO\s+auth\.(users|identities)/i.test(output)) throw new Error('Fresh baseline must not create Auth accounts.');
const targets = [
  [resolve(destination, baselines[0]), output],
  [resolve(root, 'staging/source-manifest.json'), JSON.stringify(manifest, null, 2) + '\n'],
];
for (const [path, content] of targets) {
  if ((await readFile(path, 'utf8')).replace(/\r\n/g, '\n') !== content) throw new Error(`${path} differs from its source manifest. Review the change; do not regenerate a deployed baseline.`);
}
console.log(`Fresh baseline verified: ${files.length - Object.keys(exclusions).length} source migrations, ${Object.keys(exclusions).length} documented exclusions.`);
